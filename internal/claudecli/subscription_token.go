package claudecli

import (
	"context"
	"errors"
	"fmt"
	"os"
	"os/exec"
	"strconv"
	"strings"
	"sync"
	"sync/atomic"
	"time"
)

const SubscriptionTokenEnv = "CLAUDE_CODE_OAUTH_TOKEN"

// SubscriptionTokenStore belongs to LCR. It never modifies Claude's own login.
type SubscriptionTokenStore interface {
	Read(context.Context) (string, error)
	Write(context.Context, string) error
	Delete(context.Context) error
	Description() string
}

type SubscriptionTokenInfo struct {
	Saved   bool
	Storage string
	Error   string
}

type subscriptionTokenState struct {
	token string
	info  SubscriptionTokenInfo
}

// SubscriptionTokenManager publishes an immutable memory snapshot. Credential
// I/O runs only in startup/background commands, never in render or Update.
type SubscriptionTokenManager struct {
	store SubscriptionTokenStore
	opMu  sync.Mutex
	state atomic.Pointer[subscriptionTokenState]
}

func NewSubscriptionTokenManager(store SubscriptionTokenStore) *SubscriptionTokenManager {
	m := &SubscriptionTokenManager{store: store}
	m.publish("", nil)
	return m
}

func (m *SubscriptionTokenManager) publish(token string, err error) {
	info := SubscriptionTokenInfo{Saved: token != "", Storage: m.store.Description()}
	if err != nil {
		info.Error = err.Error()
	}
	m.state.Store(&subscriptionTokenState{token: token, info: info})
}

func (m *SubscriptionTokenManager) Info() SubscriptionTokenInfo {
	return m.state.Load().info
}

func (m *SubscriptionTokenManager) Refresh(ctx context.Context) error {
	m.opMu.Lock()
	defer m.opMu.Unlock()
	token, err := m.store.Read(ctx)
	if err == nil && token != "" {
		err = ValidateSubscriptionToken(token)
	}
	if err != nil {
		token = ""
	}
	m.publish(token, err)
	return err
}

func ValidateSubscriptionToken(token string) error {
	// setup-token emits a single opaque ASCII credential. Reject control bytes
	// and oversized input without ever including the credential in an error.
	if len(token) == 0 || len(token) > 16*1024 {
		return errors.New("paste the subscription token generated by `claude setup-token`")
	}
	for _, ch := range token {
		if ch <= ' ' || ch > '~' {
			return errors.New("Claude subscription token must be a single line without spaces")
		}
	}
	return nil
}

func (m *SubscriptionTokenManager) Save(ctx context.Context, token string) error {
	token = strings.TrimSpace(token)
	if err := ValidateSubscriptionToken(token); err != nil {
		return err
	}
	m.opMu.Lock()
	defer m.opMu.Unlock()
	if err := m.store.Write(ctx, token); err != nil {
		return err
	}
	m.publish(token, nil)
	return nil
}

func (m *SubscriptionTokenManager) Remove(ctx context.Context) error {
	m.opMu.Lock()
	defer m.opMu.Unlock()
	if err := m.store.Delete(ctx); err != nil {
		return err
	}
	m.publish("", nil)
	return nil
}

func (m *SubscriptionTokenManager) Apply(cmd *exec.Cmd) error {
	base := cmd.Env
	if base == nil {
		base = cmd.Environ()
	}
	// An explicit operator environment always wins over the LCR-saved token.
	if subscriptionCredentialOverride(base) != "" {
		return nil
	}
	state := m.state.Load()
	if state.info.Error != "" {
		return fmt.Errorf("Claude subscription token unavailable: %s. Open /claude-auth to reconnect or remove the saved token", state.info.Error)
	}
	if state.token == "" {
		return nil
	}
	// Copy the slice so applying credentials cannot mutate another command's
	// environment or expose the token through LCR's process-wide environment.
	env := make([]string, 0, len(base)+1)
	for _, entry := range base {
		if !strings.HasPrefix(entry, SubscriptionTokenEnv+"=") {
			env = append(env, entry)
		}
	}
	cmd.Env = append(env, SubscriptionTokenEnv+"="+state.token)
	return nil
}

func subscriptionCredentialOverride(env []string) string {
	value := func(key string) string {
		for i := len(env) - 1; i >= 0; i-- {
			if result, ok := strings.CutPrefix(env[i], key+"="); ok {
				return strings.TrimSpace(result)
			}
		}
		return ""
	}
	for _, key := range []string{"CLAUDE_CODE_USE_BEDROCK", "CLAUDE_CODE_USE_VERTEX", "CLAUDE_CODE_USE_FOUNDRY"} {
		if enabled, _ := strconv.ParseBool(value(key)); enabled {
			return key
		}
	}
	for _, key := range []string{"ANTHROPIC_AUTH_TOKEN", "ANTHROPIC_API_KEY", SubscriptionTokenEnv, "ANTHROPIC_PROFILE"} {
		if value(key) != "" {
			return key
		}
	}
	return ""
}

func SubscriptionTokenEnvironmentOverride() string {
	return subscriptionCredentialOverride(os.Environ())
}

var subscriptionTokens atomic.Pointer[SubscriptionTokenManager]

func SubscriptionTokens() *SubscriptionTokenManager {
	if manager := subscriptionTokens.Load(); manager != nil {
		return manager
	}
	manager := NewSubscriptionTokenManager(NewSubscriptionTokenStore(""))
	if subscriptionTokens.CompareAndSwap(nil, manager) {
		return manager
	}
	return subscriptionTokens.Load()
}

// InitializeSubscriptionTokens runs before services or the TUI start. A failed
// read is retained for the connection dialog; it does not prevent LCR startup.
func InitializeSubscriptionTokens(ctx context.Context, dataDir string) error {
	manager := NewSubscriptionTokenManager(NewSubscriptionTokenStore(dataDir))
	ctx, cancel := context.WithTimeout(ctx, 10*time.Second)
	defer cancel()
	var err error
	if SubscriptionTokenEnvironmentOverride() == "" {
		err = manager.Refresh(ctx)
	}
	subscriptionTokens.Store(manager)
	return err
}

func ApplySubscriptionToken(cmd *exec.Cmd) error {
	return SubscriptionTokens().Apply(cmd)
}

func HasSubscriptionToken() bool {
	return strings.TrimSpace(os.Getenv(SubscriptionTokenEnv)) != "" || SubscriptionTokens().state.Load().token != ""
}
